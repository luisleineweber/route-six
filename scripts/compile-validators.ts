import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import Ajv2020 from 'ajv/dist/2020';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone';
import common from '../docs/schema/common.schema.json';
import game from '../docs/schema/game.schema.json';
import acquisition from '../docs/schema/acquisition.schema.json';
import root from '../docs/schema/planner-data.schema.json';

const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(common).addSchema(game).addSchema(acquisition).addSchema(root);
const { games: _games, ...properties } = root.properties;
const sharedId = 'https://pokemon-playthrough-planner.local/schema/shared-data.schema.json';
ajv.addSchema({ $id: sharedId, type: 'object', additionalProperties: false,
  required: ['schemaVersion', 'references', 'pokemon'], properties });

// Standalone output still calls require() for AJV helpers, which browsers cannot run.
// The runtime helpers are self-contained functions, so their source is inlined.
// The format table uses module-level helpers, so it stays a named ES import.
const require = createRequire(import.meta.url);
let code = standaloneCode(ajv, { checkShape: root.$id, checkSharedShape: sharedId })
  .replace(/require\("(ajv\/dist\/runtime\/[\w-]+)"\)\.default/g, (_match, path: string) => `(${require(path).default.toString()})`)
  .replace(/require\("ajv-formats\/dist\/formats"\)\.fullFormats/g, 'fullFormats');
const leftover = code.match(/require\([^)]*\)/);
if (leftover) throw new Error(`Unsupported require in standalone validator: ${leftover[0]}`);
code = 'import { fullFormats } from "ajv-formats/dist/formats.js";\n' + code;
await writeFile(new URL('../src/data/compiled-shapes.mjs', import.meta.url), '// Generated by scripts/compile-validators.ts.\n' + code);
